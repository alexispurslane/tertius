using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Tertius.Unions;

/// <summary>Writes the source of one union from its <see cref="UnionModel"/>.</summary>
internal static class UnionWriter
{
    // HashCode.Combine takes at most eight values, so longer cases fold into it seven at a time.
    private const int CombineAtOnce = 7;

    public static string Write(UnionModel union)
    {
        var text = new StringBuilder();
        text.AppendLine("// <auto-generated/>");
        text.AppendLine("// The union generator in analyzers/Tertius.Unions wrote this file (docs/plans/union-tooling.md).");
        text.AppendLine("#nullable enable");
        if (union.Namespace != null)
            text.AppendLine($"namespace {union.Namespace};");
        text.AppendLine();
        foreach (string container in union.Containers)
            text.AppendLine(container).AppendLine("{");
        Body(text, union);
        foreach (string _ in union.Containers)
            text.AppendLine("}");
        return text.ToString();
    }

    private static void Body(StringBuilder text, UnionModel union)
    {
        text.AppendLine("[global::System.Runtime.CompilerServices.Union]");
        text.AppendLine($"{(union.IsReadOnly ? "readonly " : "")}partial struct {union.Name} : global::System.IEquatable<{union.Name}>");
        text.AppendLine("{");
        Fields(text, union);
        Constructors(text, union);
        Reads(text, union);
        Equality(text, union);
        text.AppendLine("}");
    }

    /// <summary>The kind constants, the slots and the kind.</summary>
    private static void Fields(StringBuilder text, UnionModel union)
    {
        string none = union.HasZeroCase ? "" : "KindNone = 0, ";
        text.AppendLine($"    private const byte {none}{string.Join(", ", union.Cases.Select(c => $"{c.KindName} = {c.Kind}"))};");
        text.AppendLine();
        for (int i = 0; i < union.Slots.Count; i++)
        {
            text.AppendLine($"    // Holds {union.Slots[i].Holds}.");
            SlotModel slot = union.Slots[i];
            string nullable = slot.IsReference && !slot.Type.EndsWith("?") ? "?" : "";
            text.AppendLine($"    private readonly {slot.Type}{nullable} slot{i};");
        }

        text.AppendLine("    private readonly byte kind;");
    }

    /// <summary>The constructor and the implicit conversion of each case.</summary>
    private static void Constructors(StringBuilder text, UnionModel union)
    {
        string name = union.Name;
        foreach (CaseModel c in union.Cases)
        {
            text.AppendLine();
            text.AppendLine($"    /// <summary>A value that holds <paramref name=\"value\"/>.</summary>");
            text.AppendLine($"    public {name}({c.Type} value)");
            text.AppendLine("    {");
            foreach (ValueModel value in c.Values)
                text.AppendLine($"        slot{value.Slot} = value{(value.Property == null ? "" : "." + value.Property)};");
            text.AppendLine($"        kind = {c.KindName};");
            text.AppendLine("    }");
            text.AppendLine();
            text.AppendLine($"    /// <summary>A value that holds <paramref name=\"value\"/>.</summary>");
            text.AppendLine($"    public static implicit operator {name}({c.Type} value) => new(value);");
        }

    }

    /// <summary><c>HasValue</c>, <c>Value</c> and the <c>TryGetValue</c> of each case.</summary>
    private static void Reads(StringBuilder text, UnionModel union)
    {
        text.AppendLine();
        text.AppendLine("    /// <summary>False only for the empty value, which holds no case.</summary>");
        text.AppendLine($"    public bool HasValue => {(union.HasZeroCase ? "true" : "kind != KindNone")};");
        text.AppendLine();
        // A union with a zero case has no empty value, so its Value is never null. Only its constructors set the kind.
        text.AppendLine(union.HasZeroCase
            ? "    /// <summary>The held case, boxed. For debugging only.</summary>"
            : "    /// <summary>The held case, boxed, or null for the empty value. For debugging only.</summary>");
        text.AppendLine($"    public object{(union.HasZeroCase ? "" : "?")} Value => kind switch");
        text.AppendLine("    {");
        foreach (CaseModel c in union.Cases)
            text.AppendLine($"        {c.KindName} => {Read(union, c)},");
        text.AppendLine(union.HasZeroCase
            ? "        _ => throw new global::System.Diagnostics.UnreachableException($\"The kind {kind} is no case.\")"
            : "        _ => null");
        text.AppendLine("    };");
        foreach (CaseModel c in union.Cases)
        {
            text.AppendLine();
            text.AppendLine($"    /// <summary>True and the case when this value holds a {c.Display}. Otherwise false and the default.</summary>");
            text.AppendLine($"    public bool TryGetValue(out {c.Type} value)");
            text.AppendLine("    {");
            text.AppendLine($"        value = kind == {c.KindName} ? {Read(union, c)} : default;");
            text.AppendLine($"        return kind == {c.KindName};");
            text.AppendLine("    }");
        }

    }

    /// <summary>Equality, the hash, the operators and <c>ToString</c>.</summary>
    private static void Equality(StringBuilder text, UnionModel union)
    {
        string name = union.Name;
        text.AppendLine();
        text.AppendLine("    /// <summary>True when both values hold the same case with equal values, or both are empty.</summary>");
        text.AppendLine($"    public bool Equals({name} other) => kind == other.kind && kind switch");
        text.AppendLine("    {");
        foreach (CaseModel c in union.Cases.Where(c => c.Values.Count > 0))
            text.AppendLine($"        {c.KindName} => {string.Join(" && ", c.Values.Select(v => $"SlotEquals(slot{v.Slot}, other.slot{v.Slot})"))},");
        text.AppendLine("        _ => true");
        text.AppendLine("    };");
        text.AppendLine();
        text.AppendLine("    /// <summary>True when <paramref name=\"obj\"/> is a value of this union that equals this one.</summary>");
        text.AppendLine($"    public override bool Equals(object? obj) => obj is {name} other && Equals(other);");
        text.AppendLine();
        text.AppendLine("    /// <summary>The hash of the kind and the values of the held case.</summary>");
        text.AppendLine("    public override int GetHashCode() => kind switch");
        text.AppendLine("    {");
        foreach (CaseModel c in union.Cases.Where(c => c.Values.Count > 0))
            text.AppendLine($"        {c.KindName} => {Hash(c)},");
        text.AppendLine("        _ => kind");
        text.AppendLine("    };");
        text.AppendLine();
        text.AppendLine("    /// <summary>True when both values hold the same case with equal values, or both are empty.</summary>");
        text.AppendLine($"    public static bool operator ==({name} a, {name} b) => a.Equals(b);");
        text.AppendLine();
        text.AppendLine("    /// <summary>True when the values hold different cases, or one case with different values.</summary>");
        text.AppendLine($"    public static bool operator !=({name} a, {name} b) => !a.Equals(b);");
        text.AppendLine();
        text.AppendLine("    /// <summary>The name of the union and the held case, or <c>(none)</c> for the empty value.</summary>");
        text.AppendLine(union.HasZeroCase
            ? $"    public override string ToString() => $\"{name}({{Value}})\";"
            : $"    public override string ToString() => kind == KindNone ? \"{name}(none)\" : $\"{name}({{Value}})\";");
        text.AppendLine();
        text.AppendLine("    // Each value compares with its own Equals, as a record compares its fields, so NaN equals NaN.");
        text.AppendLine("    private static bool SlotEquals<T>(T a, T b) => global::System.Collections.Generic.EqualityComparer<T>.Default.Equals(a, b);");
    }

    /// <summary>
    /// The expression that builds case <paramref name="c"/> from its slots. A reference slot is nullable, but the case
    /// that holds it stored its own value there, so the read says that it is not null.
    /// </summary>
    private static string Read(UnionModel union, CaseModel c) => c.Whole
        ? $"slot{c.Values[0].Slot}"
        : $"new {c.Type}({string.Join(", ", c.Values.Select(v => $"slot{v.Slot}{(union.Slots[v.Slot].IsReference ? "!" : "")}"))})";

    /// <summary>The hash of the kind and the values of case <paramref name="c"/>.</summary>
    private static string Hash(CaseModel c)
    {
        string hash = "kind";
        IEnumerable<string> values = c.Values.Select(v => $"slot{v.Slot}");
        while (values.Any())
        {
            hash = $"global::System.HashCode.Combine({hash}, {string.Join(", ", values.Take(CombineAtOnce))})";
            values = values.Skip(CombineAtOnce);
        }

        return hash;
    }
}

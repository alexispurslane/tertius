using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Tertius.Slop;

/// <summary>One parsed C# file of a codebase.</summary>
/// <param name="Path">The path relative to the root of the repository, with <c>/</c> between folders.</param>
/// <param name="Tree">The syntax of the file.</param>
public sealed record SourceFile(string Path, SyntaxTree Tree)
{
    // C# 15 preview, so that a built-in union parses. The metrics never read a doc comment, so the parser keeps each one
    // as plain comment trivia.
    private static readonly CSharpParseOptions ParseOptions =
        new(languageVersion: LanguageVersion.Preview, documentationMode: DocumentationMode.None);

    /// <summary>
    /// Whether a tool wrote the file: its name ends in <c>.g.cs</c>, or a comment before its first code holds the marker
    /// <c>&lt;auto-generated</c>, as the compiler's own test for generated code reads it.
    /// </summary>
    public bool IsGenerated => Path.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase) || HasGeneratedMarker;

    /// <summary>The number of lines in the whole file that hold code, inside functions or not.</summary>
    public int Sloc => Tree.GetRoot().DescendantTokens().CodeLineCount();

    /// <summary>Every function in the file, in the order of the source.</summary>
    public IEnumerable<Function> Functions => Function.In(Tree.GetRoot());

    private bool HasGeneratedMarker =>
        Tree.GetRoot().GetLeadingTrivia().Any(trivia =>
            trivia.IsKind(SyntaxKind.SingleLineCommentTrivia) &&
            trivia.ToString().Contains("<auto-generated", StringComparison.Ordinal));

    /// <summary>The file at <paramref name="path"/> with the text <paramref name="text"/>.</summary>
    public static SourceFile Parse(string path, string text) =>
        new(path, CSharpSyntaxTree.ParseText(text: text, options: ParseOptions, path: path));
}

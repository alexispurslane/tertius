using System.Collections.Immutable;
using AwesomeAssertions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Text;

namespace Tertius.Style.Tests;

/// <summary>
/// TS0003: the null-forgiving operator. The rule reports it in every file, and <c>.editorconfig</c> turns it off outside
/// <c>src</c>.
/// </summary>
public sealed class NullForgivingTests
{
    [Fact]
    public async Task TheNullForgivingOperatorIsReported() =>
        (await Analysis.Ids("TS0003", """
                                      public static class C
                                      {
                                          public static string Name(string? name) => name!;
                                      }
                                      """)).Should().Equal("TS0003");

    [Fact]
    public async Task ANullForgivingNullLiteralIsReported() =>
        (await Analysis.Ids("TS0003", """
                                      public class C
                                      {
                                          public string Name = null!;
                                      }
                                      """)).Should().Equal("TS0003");

    [Fact]
    public async Task TheLogicalNotIsNotReported() =>
        (await Analysis.Ids("TS0003", """
                                      public static class C
                                      {
                                          public static bool Flip(bool on) => !on;
                                      }
                                      """)).Should().BeEmpty();

    [Fact]
    public async Task ATestForNullIsNotReported() =>
        (await Analysis.Ids("TS0003", """
                                      public static class C
                                      {
                                          public static int Length(string? name) => name is { } known ? known.Length : 0;
                                      }
                                      """)).Should().BeEmpty();

    [Fact]
    public async Task GeneratedCodeIsNotAnalyzed() =>
        (await Analysis.Ids("TS0003", """
                                      // <auto-generated/>
                                      public static class C
                                      {
                                          public static string Name(string? name) => name!;
                                      }
                                      """)).Should()
        .BeEmpty("generated code that reads a reference slot is the one place for it");

    [Fact]
    public async Task TheRepositoryEditorConfigKeepsTheRuleToSrc()
    {
        CancellationToken cancel = TestContext.Current.CancellationToken;
        string root = Repository.Root();
        using AdhocWorkspace workspace = new();
        Project project = workspace.AddProject(ProjectInfo.Create(id: ProjectId.CreateNewId(),
            version: VersionStamp.Default, name: "Probe", assemblyName: "Probe", language: LanguageNames.CSharp,
            compilationOptions: TestCompilation.Options, parseOptions: TestCompilation.Parse,
            metadataReferences: TestCompilation.References));
        string editorConfig = Path.Combine(root, ".editorconfig");
        project = project.AddAnalyzerConfigDocument(name: ".editorconfig",
            text: SourceText.From(await File.ReadAllTextAsync(editorConfig, cancel)), filePath: editorConfig).Project;
        string[] folders = ["src", "tests", "benchmarks", "analyzers"];
        foreach (string folder in folders)
            project = project.AddDocument(name: "Probe.cs",
                text: $"public static class In_{folder} {{ public static string Name(string? name) => name!; }}",
                filePath: Path.Combine(path1: root, path2: folder, path3: "Probe", path4: "Probe.cs")).Project;
        Compilation compilation = await project.GetCompilationAsync(cancel) ??
                                  throw new InvalidOperationException("The project has no compilation.");

        ImmutableArray<Diagnostic> found = await compilation
            .WithAnalyzers([new StyleAnalyzer()], project.AnalyzerOptions).GetAnalyzerDiagnosticsAsync(cancel);

        found.Select(diagnostic => Path.GetRelativePath(root, diagnostic.Location.SourceTree!.FilePath))
            .Should().Equal([Path.Combine("src", "Probe", "Probe.cs")], "the tests, the benchmarks and the analyzers " +
                                                                        "are not engine code");
    }
}
